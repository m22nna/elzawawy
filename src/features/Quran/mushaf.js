const countUpTo = (arr, page) => {
  let n = 0;
  while (n < arr.length && arr[n] <= page) n++;
  return Math.max(1, n);
};

export const juzOfPage = (page) => countUpTo(JUZ_LABEL_FROM, page);
export const hizbOfPage = (page) => countUpTo(HIZB_LABEL_FROM, page);

export const clampPage = (n) => Math.min(TOTAL_PAGES, Math.max(1, Math.trunc(Number(n)) || 1));
export const firstPageOfSurah = (id) => SURAH_FIRST_PAGE[Math.min(114, Math.max(1, Number(id) || 1)) - 1];
export const lastPageOfSurah = (id) => SURAH_LAST_PAGE[Math.min(114, Math.max(1, Number(id) || 1)) - 1];

// "٢-٤٩" أو "١" لو السورة في صفحة واحدة
export const pageRangeOfSurah = (id) => {
  const a = firstPageOfSurah(id);
  const b = lastPageOfSurah(id);
  return a === b ? [a] : [a, b];
};

